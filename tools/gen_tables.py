"""BIOFORGE's tables: firmware/gen/bio_tables.h. The chip has no FPU, so everything the engine needs from sin, tan,
exp2 and log2 is computed here once, as integers.

  python3 tools/gen_tables.py           write firmware/gen/bio_tables.h
  python3 tools/gen_tables.py --check   fail if it differs from what this script makes

Frequencies in the engine are log2(Hz) in Q16 ("lf"): 1 Hz is 0, 440 Hz is 575 919, a semitone 5461.33. The filter and
resonator tables run from LF_LO (16 Hz) in steps of 1/32 octave."""
import math
import sys
from pathlib import Path

FS = 44100
OUT = Path(__file__).resolve().parent.parent / "firmware" / "gen" / "bio_tables.h"
LF_LO_OCT = 4.0            # 16 Hz
STEPS_PER_OCT = 32
N_LF = int((14.4 - LF_LO_OCT) * STEPS_PER_OCT) + 2   # to 21.6 kHz


def arr(name, ctype, vals, per=12):
    lines = []
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    out = []
    out.append("/* SPDX-License-Identifier: GPL-3.0-only */\n/* Copyright (C) 2026 Joakim (joakimskurk) */\n")
    out.append("/* generated by tools/gen_tables.py: never edit (run it again) */\n")
    out.append("#ifndef BIO_TABLES_H\n#define BIO_TABLES_H\n#include <stdint.h>\n\n")
    out.append(f"#define BIO_LF_LO {int(LF_LO_OCT * 65536)}  /* lf of the first filter entry (16 Hz) */\n")
    out.append(f"#define BIO_LF_N {N_LF}\n#define BIO_LF_SHIFT 11  /* 1/32 octave = 2048 lf */\n\n")

    # sine, a full turn in 1024 steps (and one more for the interpolation), Q15
    sin_t = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]
    out.append("/* sin, a turn in 1024, Q15 */\n" + arr("BIO_SIN", "int16_t", sin_t, 16))

    # phase increment of 1 Hz * 2^(j/256): shifted left by the octave of lf
    inc = [round((2 ** 32 / FS) * 2 ** (j / 256)) for j in range(257)]
    out.append("/* a 32-bit phase's increment at 2^(j/256) Hz (shift left by lf's octave) */\n" +
               arr("BIO_INC1", "uint32_t", inc, 10))

    # 2^(j/256), Q16
    e2 = [round(65536 * 2 ** (j / 256)) for j in range(257)]
    out.append("/* 2^(j/256), Q16 */\n" + arr("BIO_EXP2", "uint32_t", e2, 10))

    # log2(1 + j/256), Q16
    l2 = [round(65536 * math.log2(1 + j / 256)) for j in range(257)]
    out.append("/* log2(1 + j/256), Q16 */\n" + arr("BIO_LOG2", "uint32_t", l2, 10))

    # the TPT state-variable filter's g = tan(pi f / FS), Q24, capped below Nyquist
    tg, mc = [], []
    for i in range(N_LF):
        f = 2 ** (LF_LO_OCT + i / STEPS_PER_OCT)
        x = min(f, 0.45 * FS) / FS
        tg.append(round((1 << 24) * math.tan(math.pi * x)))
        y = min(f, 15000.0) / FS                     # the resonators stay under 15 kHz
        mc.append(round((1 << 30) * 2 * math.sin(math.pi * y)))
    out.append("/* tan(pi f / FS), Q24, f = 2^(4 + i/32) Hz (to 0.45 FS) */\n" + arr("BIO_TAN", "int32_t", tg, 10))
    out.append("/* the magic circle's 2 sin(pi f / FS), Q30 (to 15 kHz) */\n" + arr("BIO_MC", "int32_t", mc, 8))

    out.append("\n#endif\n")
    text = "".join(out)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT}: differs from what tools/gen_tables.py makes (run it)")
            return 1
        print("bio_tables.h: up to date")
        return 0
    OUT.write_text(text)
    print(f"{OUT}: {len(text)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
